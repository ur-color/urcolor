/**
 * `a98-rgb` — Adobe RGB (1998). Gamma transfer of 563/256, D65 white.
 */

import { makeRgbSpace, type XyzBridge } from "./rgbSpace";

const sign = (c: number): number => (c < 0 ? -1 : 1);

export const a98: XyzBridge = makeRgbSpace({
  toLinear: (c) => sign(c) * Math.abs(c) ** (563 / 256),
  toGamma: (c) => sign(c) * Math.abs(c) ** (256 / 563),
  toXyzMatrix: [
    [0.5766690429101305, 0.1855582379065463, 0.1882286462349947],
    [0.29734497525053605, 0.6273635662554661, 0.07529145849399788],
    [0.02703136138641234, 0.07068885253582723, 0.9913375368376388],
  ],
  fromXyzMatrix: [
    [2.0415879038107465, -0.5650069742788596, -0.34473135077832406],
    [-0.9692436362808795, 1.8759675015077202, 0.04155505740717557],
    [0.013444280632031142, -0.11836239223101838, 1.0151749943912054],
  ],
});
